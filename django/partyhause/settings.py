    EMAIL_USE_TLS = os.environ.get('EMAIL_USE_TLS', 'False').lower() == 'true'
    DEFAULT_FROM_EMAIL = 'PartyHause <dev@partyhause.local>'
    SERVER_EMAIL = 'PartyHause <dev@partyhause.local>'

